const {chromium}=require('playwright'); const assert=require('node:assert/strict'); const path=require('node:path');
(async()=>{
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage(); const errors=[]; page.on('pageerror', e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8000');
await page.getByRole('button',{name:'Upload source package',exact:true}).click();
await page.locator('#pdf-files').setInputFiles(['shared-brief.pdf','role-card.pdf','no-text.pdf'].map(f=>path.resolve('tests/fixtures',f)));
await page.getByRole('button',{name:'Continue with sources',exact:true}).waitFor({state:'visible'});
await page.waitForFunction(()=>!document.querySelector('#pdf-create').disabled);
const results=await page.locator('#pdf-results').innerText();
assert.match(results,/No readable text found/); assert.match(results,/1 pages read/);
await page.locator('#pdf-package-form [name=title]').fill('Imported PDF test');
await page.getByRole('button',{name:'Continue with sources',exact:true}).click();
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('negotiation-workspace-v1')));
assert.equal(saved.package.sources.length,2);
assert.match(saved.package.sources[0].pages[0].text,/delivery schedule/);
assert.equal(saved.package.pipeline[0].status,'complete');
assert.equal(saved.package.facts.length,0);
await page.reload();
assert.equal(await page.getByRole('heading',{name:'Imported PDF test'}).count(),1);
await page.getByRole('button',{name:'Upload documents',exact:true}).click();
await page.locator('#pdf-files').setInputFiles({name:'broken.pdf',mimeType:'application/pdf',buffer:Buffer.from('not a pdf')});
await page.waitForFunction(()=>document.querySelector('#pdf-results').textContent.includes('Could not read'));
assert.equal(await page.locator('#pdf-create').isDisabled(),true);
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.getByRole('button',{name:'Cancel',exact:true}).first().click();
assert.deepEqual(errors,[]); await browser.close(); console.log('PASS: multi-PDF extraction, page provenance, blank/malformed PDF errors, package creation, persistence, mobile dialog');
})().catch(e=>{console.error(e);process.exit(1)});
